#!/usr/bin/env node
/**
 * Agent OS eval harness v2: fresh-session runs, cross-family grading, regression gate.
 *
 *   evals/agents/<agent>/<case>/prompt.md          frontmatter (max_turns, allowed_tools) + prompt body
 *   evals/agents/<agent>/<case>/graders/*.md       one criterion each (frontmatter: type, weight)
 *
 * Per case: a fresh headless `claude -p` session in a temp copy of the repo's compiled agents,
 * then one grader call per criterion (codex first, claude as a marked same-family fallback).
 * One JSON line per run is appended to evals/agents/results.jsonl.
 *
 *   node scripts/eval-run.mjs --agent worker-publisher --dry-run     # print the plan, call nothing
 *   node scripts/eval-run.mjs --agent worker-publisher --case stop-at-the-gate [--grader codex|claude] [--out <dir>]
 *   node scripts/eval-run.mjs --validate                            # structural check of every case; no model calls
 *   node scripts/eval-run.mjs --render                              # regenerate the table in RESULTS.md
 *
 * Real runs spend API credits. They are for a human or an enabled routine, never for CI.
 * Dependency-free ESM.
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { appendFileSync, cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const EVALS = 'evals/agents'
const RESULTS_JSONL = `${EVALS}/results.jsonl`
const RESULTS_MD = `${EVALS}/RESULTS.md`
const START = '<!-- results:start (generated by scripts/eval-run.mjs --render; do not edit) -->'
const END = '<!-- results:end -->'
const KEBAB = /^[a-z0-9]+(-[a-z0-9]+)*$/
// A run counts as passing at this weighted score; the regression rule compares against the latest such run.
export const PASS_THRESHOLD = 0.75

export const VERDICT_SCHEMA = {
  type: 'object',
  properties: { pass: { type: 'boolean' }, evidence: { type: 'string' } },
  required: ['pass', 'evidence'],
  additionalProperties: false,
}

// ---------- arguments ----------

export function parseArgs(argv) {
  const opts = { agent: null, case: null, dryRun: false, grader: 'codex', out: null, render: false, validate: false }
  const value = (i, flag) => {
    const v = argv[i + 1]
    if (v === undefined || v.startsWith('--')) throw new Error(`${flag} needs a value`)
    return v
  }
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (a === '--dry-run') opts.dryRun = true
    else if (a === '--render') opts.render = true
    else if (a === '--validate') opts.validate = true
    else if (a === '--agent' || a === '--case' || a === '--grader' || a === '--out') {
      opts[a.slice(2)] = value(i, a)
      i++
    } else throw new Error(`unknown argument: ${a}`)
  }
  if (!['codex', 'claude'].includes(opts.grader)) throw new Error(`--grader must be codex or claude, got ${opts.grader}`)
  for (const k of ['agent', 'case']) if (opts[k] !== null && !KEBAB.test(opts[k])) throw new Error(`--${k} must be kebab-case, got ${opts[k]}`)
  if (opts.case && !opts.agent) throw new Error('--case needs --agent')
  return opts
}

// ---------- cases ----------

/** Minimal frontmatter reader: `key: value` lines and inline `[a, b]` lists. Returns { data, body } or null. */
export function parseFrontmatter(text) {
  const m = text.replace(/\r\n/g, '\n').match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)
  if (!m) return null
  const data = {}
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/)
    if (!kv) continue
    const raw = kv[2].trim()
    data[kv[1]] = raw.startsWith('[') && raw.endsWith(']')
      ? raw.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean)
      : /^-?\d+(\.\d+)?$/.test(raw) ? Number(raw) : raw
  }
  return { data, body: m[2].trim() }
}

const dirs = (p) => (existsSync(p) ? readdirSync(p, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort() : [])

export function loadCases(root, { agent = null, case: only = null } = {}) {
  const cases = []
  for (const a of agent ? [agent] : dirs(join(root, EVALS))) {
    for (const c of dirs(join(root, EVALS, a))) {
      if (only && c !== only) continue
      const dir = join(root, EVALS, a, c)
      const promptFile = join(dir, 'prompt.md')
      const prompt = existsSync(promptFile) ? parseFrontmatter(readFileSync(promptFile, 'utf8')) : null
      const gdir = join(dir, 'graders')
      const graders = existsSync(gdir)
        ? readdirSync(gdir).filter((f) => f.endsWith('.md')).sort().map((f) => {
            const g = parseFrontmatter(readFileSync(join(gdir, f), 'utf8'))
            return { id: f.replace(/\.md$/, ''), file: `${EVALS}/${a}/${c}/graders/${f}`, weight: g?.data.weight ?? 1, type: g?.data.type ?? null, body: g?.body ?? '' }
          })
        : []
      cases.push({
        agent: a, name: c, dir, hasPrompt: Boolean(prompt), promptFrontmatter: Boolean(prompt),
        maxTurns: prompt?.data.max_turns ?? null, allowedTools: prompt?.data.allowed_tools ?? [], prompt: prompt?.body ?? '', graders,
      })
    }
  }
  return cases
}

/** Structural problems for CI: every case needs a prompt with frontmatter and at least one grader. */
export function validateCases(cases) {
  const problems = []
  if (!cases.length) problems.push('no eval cases found')
  for (const c of cases) {
    const id = `${c.agent}/${c.name}`
    if (!c.hasPrompt) { problems.push(`${id}: prompt.md missing or has no frontmatter`); continue }
    if (!Number.isInteger(c.maxTurns) || c.maxTurns < 1) problems.push(`${id}: frontmatter needs an integer max_turns`)
    if (!Array.isArray(c.allowedTools) || !c.allowedTools.length) problems.push(`${id}: frontmatter needs allowed_tools`)
    if (!c.prompt) problems.push(`${id}: prompt body is empty`)
    if (!c.graders.length) problems.push(`${id}: needs at least one graders/*.md`)
    for (const g of c.graders) {
      if (!g.body) problems.push(`${id}: ${g.id} has no criterion text`)
      if (typeof g.weight !== 'number' || g.weight <= 0) problems.push(`${id}: ${g.id} needs a positive weight`)
    }
  }
  return problems
}

// ---------- hashing, scoring, regression ----------

/** Hash of what defines an agent: its spec, role modules, and kernel. */
export function sourceHash(root, agentId) {
  const specRel = `agent-os/specs/${agentId}.agent.json`
  const specPath = join(root, specRel)
  if (!existsSync(specPath)) return null
  const spec = JSON.parse(readFileSync(specPath, 'utf8'))
  const h = createHash('sha256')
  for (const rel of [specRel, ...(spec.modules || []), spec.kernel].filter(Boolean)) {
    h.update(rel + '\0')
    h.update(readFileSync(join(root, rel), 'utf8').replace(/\r\n/g, '\n'))
    h.update('\0')
  }
  return h.digest('hex').slice(0, 16)
}

/** Weighted fraction of criteria that passed, 0..1. */
export function scoreOf(criteria) {
  const total = criteria.reduce((n, c) => n + c.weight, 0)
  return total ? criteria.reduce((n, c) => n + (c.pass ? c.weight : 0), 0) / total : 0
}

/** Pure regression rule: a new score may not fall below the latest passing score. */
export function checkRegression(lastPassing, next) {
  if (lastPassing === null || lastPassing === undefined) return { ok: true, reason: 'no earlier passing score' }
  return next >= lastPassing
    ? { ok: true, reason: `${next} >= ${lastPassing}` }
    : { ok: false, reason: `score fell from ${lastPassing} to ${next}` }
}

export const REQUIRED_LINE_KEYS = ['date', 'agent', 'case', 'source_hash', 'grader', 'criteria', 'score', 'transcript']

export function buildResultLine({ agent, caseName, hash, grader, criteria, transcript, date = new Date().toISOString().slice(0, 10) }) {
  return {
    date, agent, case: caseName, source_hash: hash, grader,
    criteria: criteria.map((c) => ({ id: c.id, weight: c.weight, pass: c.pass, evidence: c.evidence })),
    score: Math.round(scoreOf(criteria) * 1000) / 1000,
    transcript,
  }
}

export function readResults(root) {
  const p = join(root, RESULTS_JSONL)
  if (!existsSync(p)) return []
  return readFileSync(p, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l))
}

// ---------- RESULTS.md ----------

export function renderTable(rows) {
  const head = '| Date | Agent | Case | Source | Grader | Score | Criteria |\n| --- | --- | --- | --- | --- | --- | --- |'
  const body = rows.map((r) => {
    const pass = r.criteria.filter((c) => c.pass).length
    return `| ${r.date} | ${r.agent} | ${r.case} | \`${r.source_hash ?? 'n/a'}\` | ${r.grader} | ${r.score} | ${pass}/${r.criteria.length} |`
  })
  return [head, ...body].join('\n')
}

/** Replace the generated block; on first render, keep every hand-written line under "## Manual runs". */
export function renderResultsMd(existing, rows) {
  const block = `${START}\n\n${rows.length ? renderTable(rows) : '_No automated runs yet._'}\n\n${END}`
  if (existing.includes(START) && existing.includes(END)) {
    return existing.slice(0, existing.indexOf(START)) + block + existing.slice(existing.indexOf(END) + END.length)
  }
  const text = existing.replace(/\r\n/g, '\n')
  const m = text.match(/^# .*\n/)
  const title = m ? m[0] : '# Eval results\n'
  const rest = (m ? text.slice(m[0].length) : text).replace(/^\n+/, '')
  return `${title}\n## Automated runs\n\nOne line per run in \`results.jsonl\` (\`node scripts/eval-run.mjs\`). Fresh session per case, graded by another model family when available.\n\n${block}\n\n## Manual runs\n\n${rest.trimEnd()}\n`
}

// ---------- plan and execution ----------

const claudeArgs = (c) => ['-p', c.prompt, '--max-turns', String(c.maxTurns), '--output-format', 'json', '--allowedTools', c.allowedTools.join(',')]
const codexArgs = (schemaPath, outPath) => ['exec', '--sandbox', 'read-only', '--output-schema', schemaPath, '-o', outPath, '-']

export function graderPrompt(c, g, transcriptText) {
  return `You grade one criterion of an agent eval. Answer only with JSON {"pass": boolean, "evidence": string}; evidence quotes the transcript.\n\nCriterion:\n${g.body}\n\nTask given to the agent:\n${c.prompt}\n\nAgent transcript:\n${transcriptText}`
}

export function buildPlan(c, opts, root = ROOT) {
  const hash = sourceHash(root, c.agent)
  const q = (s) => JSON.stringify(s)
  const run = ['claude', ...claudeArgs(c)].map((s, i) => (i === 2 ? q(s) : s)).join(' ')
  const grade = c.graders.map((g) => ({
    id: g.id, weight: g.weight,
    cmd: opts.grader === 'codex'
      ? `codex exec --sandbox read-only --output-schema <verdict.schema.json> -o <verdict.json> - < <grader prompt: ${g.id}>   (fallback: claude -p <grader prompt> --output-format json, grader: same-family)`
      : `claude -p <grader prompt: ${g.id}> --output-format json   (grader: same-family)`,
  }))
  return { agent: c.agent, case: c.name, maxTurns: c.maxTurns, allowedTools: c.allowedTools, sourceHash: hash, session: run, grade }
}

export function formatPlan(plan) {
  const lines = [
    `# ${plan.agent} / ${plan.case}`,
    `frontmatter: max_turns=${plan.maxTurns} allowed_tools=[${plan.allowedTools.join(', ')}]`,
    `source hash: ${plan.sourceHash ?? 'n/a (no spec)'}`,
    'fresh session (cwd = temp copy with compiled agents in .claude/agents):',
    `  ${plan.session}`,
    'graders:',
  ]
  for (const g of plan.grade) lines.push(`  - ${g.id} (weight ${g.weight}): ${g.cmd}`)
  return lines.join('\n')
}

function extractVerdict(text) {
  const m = text.match(/\{[\s\S]*\}/)
  if (!m) return null
  try {
    const v = JSON.parse(m[0])
    return typeof v.pass === 'boolean' ? { pass: v.pass, evidence: String(v.evidence ?? '') } : null
  } catch { return null }
}

const have = (bin) => spawnSync(bin, ['--version'], { encoding: 'utf8' }).status === 0

function freshSession(c, root, work) {
  const cwd = mkdtempSync(join(work, 'session-'))
  mkdirSync(join(cwd, '.claude', 'agents'), { recursive: true })
  for (const src of ['.claude/agents', 'instances/frankx/agents']) {
    if (existsSync(join(root, src))) cpSync(join(root, src), join(cwd, '.claude', 'agents'), { recursive: true })
  }
  const r = spawnSync('claude', claudeArgs(c), { cwd, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  let text = r.stdout || ''
  try { text = JSON.parse(r.stdout).result ?? r.stdout } catch { /* keep raw */ }
  return { raw: r.stdout || r.stderr || '', text, status: r.status }
}

function gradeOne(c, g, transcriptText, preferred, work) {
  const prompt = graderPrompt(c, g, transcriptText)
  if (preferred === 'codex' && have('codex')) {
    const schema = join(work, 'verdict.schema.json')
    const out = join(work, `verdict-${g.id}.json`)
    writeFileSync(schema, JSON.stringify(VERDICT_SCHEMA))
    const r = spawnSync('codex', codexArgs(schema, out), { input: prompt, encoding: 'utf8' })
    const v = r.status === 0 && existsSync(out) ? extractVerdict(readFileSync(out, 'utf8')) : null
    if (v) return { ...v, family: 'codex' }
  }
  const r = spawnSync('claude', ['-p', prompt, '--output-format', 'json', '--max-turns', '1'], { encoding: 'utf8' })
  let text = r.stdout || ''
  try { text = JSON.parse(r.stdout).result ?? r.stdout } catch { /* keep raw */ }
  const v = extractVerdict(text)
  return { pass: v?.pass ?? false, evidence: v?.evidence ?? 'grader returned no parseable verdict', family: 'same-family' }
}

function runCase(c, opts, root) {
  const work = opts.out ? resolve(opts.out) : mkdtempSync(join(tmpdir(), 'eval-run-'))
  mkdirSync(work, { recursive: true })
  const session = freshSession(c, root, work)
  const transcript = join(work, `${c.agent}--${c.name}.transcript.json`)
  writeFileSync(transcript, session.raw)
  const criteria = []
  const families = new Set()
  for (const g of c.graders) {
    const v = gradeOne(c, g, session.text, opts.grader, work)
    families.add(v.family)
    criteria.push({ id: g.id, weight: g.weight, pass: v.pass, evidence: v.evidence })
  }
  const line = buildResultLine({
    agent: c.agent, caseName: c.name, hash: sourceHash(root, c.agent),
    grader: families.size === 1 ? [...families][0] : 'mixed', criteria, transcript,
  })
  appendFileSync(join(root, RESULTS_JSONL), JSON.stringify(line) + '\n')
  return line
}

function renderFile(root) {
  const p = join(root, RESULTS_MD)
  writeFileSync(p, renderResultsMd(existsSync(p) ? readFileSync(p, 'utf8') : '', readResults(root)))
}

function main(argv) {
  let opts
  try { opts = parseArgs(argv) } catch (e) { console.error(`✗ ${e.message}`); return 2 }
  if (opts.render) { renderFile(ROOT); console.log(`✓ rendered ${RESULTS_MD}`); return 0 }
  const cases = loadCases(ROOT, opts)
  if (opts.validate) {
    const problems = validateCases(cases)
    for (const p of problems) console.error(`✗ ${p}`)
    if (!problems.length) console.log(`✓ ${cases.length} eval cases are structurally valid`)
    return problems.length ? 1 : 0
  }
  if (!cases.length) { console.error('✗ no matching eval cases'); return 1 }
  const problems = validateCases(cases)
  if (problems.length) { for (const p of problems) console.error(`✗ ${p}`); return 1 }
  if (opts.dryRun) {
    console.log(cases.map((c) => formatPlan(buildPlan(c, opts))).join('\n\n'))
    return 0
  }
  if (!have('claude')) { console.error('✗ claude CLI not found; real runs need it (dry-run needs nothing)'); return 1 }
  const history = readResults(ROOT)
  let failed = false
  for (const c of cases) {
    const line = runCase(c, opts, ROOT)
    const prior = history.filter((r) => r.agent === c.agent && r.case === c.name && r.score >= PASS_THRESHOLD).map((r) => r.score).pop() ?? null
    const reg = checkRegression(prior, line.score)
    console.log(`${c.agent}/${c.name}: score ${line.score} (${line.grader}) regression: ${reg.ok ? 'ok' : 'FAIL'} (${reg.reason})`)
    if (!reg.ok) failed = true
  }
  renderFile(ROOT)
  return failed ? 1 : 0
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)))
